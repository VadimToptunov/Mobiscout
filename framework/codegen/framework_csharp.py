def _step_method(d: StepDef) -> str:
    """The step method's name — what the step does, unique within its page's step class."""
    page, el = pascal(d.page), pascal(d.element or "")
    return {
        "arrive": f"On{page}Screen",
        "tap": f"Tap{el}",
        "enter": f"Enter{el}",
        "enter_long": f"Enter{len(d.sample or '')}CharactersInto{el}",
        "is_displayed": f"See{page}Screen",
        "stays": f"StillOn{page}Screen",
        "has": f"See{el}",
        "lacks": f"NotSee{el}",
        "text_is": f"{el}Shows",
        "is_enabled": f"{el}IsEnabled",
        "app_running": "AppIsRunning",
        "back": "GoBack",
    }[d.op]


def _step_body(bm: BddModel, d: StepDef) -> Tuple[str, Set[str]]:
    """(the step's one expression, the page classes it constructs)."""
    fm = bm.fm
    page = fm.page(d.page)
    el, obj = pascal(d.element or ""), f"new {page.class_name}(Session.Driver)"
    if d.op == "arrive":
        if not d.path:
            return f"Assert.That({obj}.IsDisplayed(), Is.True)", {page.class_name}
        start = fm.page(d.path[0].page).class_name
        chain = "".join(f".Tap{pascal(c.element or '')}()" for c in d.path)
        return f"Assert.That(new {start}(Session.Driver){chain}.IsDisplayed(), Is.True)", {start}
    expression = {
        "tap": f"{obj}.Tap{el}()",
        "enter": f"{obj}.Enter{el}(value)",
        "enter_long": f"{obj}.Enter{el}({cs_value(d.sample)})",
        "back": f"{obj}.GoBack()",
        "text_is": f"Assert.That({obj}.{el}Text(), Is.EqualTo(value))",
        "is_displayed": f"Assert.That({obj}.IsDisplayed(), Is.True)",
        "stays": f"Assert.That({obj}.IsDisplayed(), Is.True)",
        "has": f"Assert.That({obj}.Has{el}(), Is.True)",
        "lacks": f"Assert.That({obj}.Lacks{el}(), Is.True)",
        "is_enabled": f"Assert.That({obj}.{el}IsEnabled(), Is.True)",
        "app_running": f"Assert.That({obj}.IsAppRunning(), Is.True)",
    }[d.op]
    return expression, {page.class_name}


def _steps_class(bm: BddModel, page_name: str) -> str:
    """The Reqnroll step-definition class driving one page."""
    blocks: List[str] = []
    for d in bm.steps_for(page_name):
        expression, _ = _step_body(bm, d)
        param = "string value" if d.has_param else ""
        blocks.append(
            f"    [{d.keyword}({cs_str(d.text)})]\n" f"    public void {_step_method(d)}({param}) => {expression};\n"
        )
    title = bm.fm.page(page_name).title
    return (
        "using MobileTests.Pages;\nusing MobileTests.Support;\nusing NUnit.Framework;\nusing Reqnroll;\n\n"
        "namespace MobileTests.StepDefinitions;\n\n"
        f"/// <summary>Steps on the {_xmldoc(title)} screen — each one a call on a page object.</summary>\n"
        f"/// <remarks>{_HEADER}</remarks>\n"
        f"[Binding]\npublic sealed class {pascal(page_name)}Steps\n{{\n" + "\n".join(blocks) + "}\n"
    )


def render_reqnroll(fm: FrameworkModel) -> Dict[str, str]:
    """The Reqnroll (NUnit) BDD suite on the page objects, as a .NET test project."""
    bm = build_bdd_model(fm)
    if not bm.features:
        return {}
    files = _base(fm, reqnroll=True)
    files["Support/Hooks.cs"] = _env().get_template("Hooks.cs.j2").render()
    for f in bm.features:
        files[f"Features/{snake(f.page)}.feature"] = render_feature(f, fm.app_package)
    used = {d.page for d in bm.steps}
    for p in fm.pages:
        if p.name in used:
            files[f"StepDefinitions/{pascal(p.name)}Steps.cs"] = _steps_class(bm, p.name)
    return files
